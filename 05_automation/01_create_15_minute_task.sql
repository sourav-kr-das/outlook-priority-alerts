USE ROLE ACCOUNTADMIN;USE SCHEMA MAIL_DB.TRIAGE;
CREATE OR REPLACE TASK SMS_PIPELINE_TASK WAREHOUSE='<WAREHOUSE_NAME>' SCHEDULE='15 MINUTES'
 USER_TASK_TIMEOUT_MS=600000 SUSPEND_TASK_AFTER_NUM_FAILURES=3
 AS CALL RUN_SMS_PIPELINE('<MAILBOX_UPN>','<DESTINATION_PHONE_E164>',80);
ALTER TASK SMS_PIPELINE_TASK SUSPEND;
SHOW TASKS LIKE 'SMS_PIPELINE_TASK' IN SCHEMA MAIL_DB.TRIAGE;
