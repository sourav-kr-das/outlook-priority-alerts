-- Use a private worksheet and never commit edited secret values.
USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS MAIL_DB;
CREATE SCHEMA IF NOT EXISTS MAIL_DB.TRIAGE;
USE SCHEMA MAIL_DB.TRIAGE;
CREATE OR REPLACE NETWORK RULE TRIAGE_EGRESS MODE=EGRESS TYPE=HOST_PORT
  VALUE_LIST=('login.microsoftonline.com:443','graph.microsoft.com:443','api.twilio.com:443');
CREATE OR REPLACE SECRET GRAPH_SECRET TYPE=GENERIC_STRING SECRET_STRING='<MS_CLIENT_SECRET>';
CREATE OR REPLACE SECRET TWILIO_SECRET TYPE=PASSWORD
  USERNAME='<TWILIO_ACCOUNT_SID>' PASSWORD='<TWILIO_AUTH_TOKEN>';
CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION TRIAGE_EAI
  ALLOWED_NETWORK_RULES=(MAIL_DB.TRIAGE.TRIAGE_EGRESS)
  ALLOWED_AUTHENTICATION_SECRETS=(MAIL_DB.TRIAGE.GRAPH_SECRET,MAIL_DB.TRIAGE.TWILIO_SECRET)
  ENABLED=TRUE;
